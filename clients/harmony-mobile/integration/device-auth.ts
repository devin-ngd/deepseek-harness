/** Unactivated device authorization owner; reuses Cordis scopes and the existing human/credential seams, with injected proof verification only. */
import { createHash } from 'node:crypto'
import type { Context } from '@deepseek-ai/cordis'
import type { PeerScope } from '@deepseek-ai/dsh-typert-protocol'
import type {} from '@deepseek-ai/dsh-client-connection'
import type {} from '@deepseek-ai/dsh-api-remote-access'
import { deviceRemotePolicy } from '../desktop-plugin/src/device-policy.ts'
import { credentialKey, type CredentialKey, type CredentialRecord } from '@deepseek-ai/dsh-credentials'
import { AuthorizationDeclinedError } from '@deepseek-ai/dsh-authorization'
import type { AuthorizationFlow } from '@deepseek-ai/dsh-authorization'
import { z } from 'zod'
import type { AuthenticatedDeviceProvider, AuthenticatedDeviceScope } from '../desktop-plugin/src/admission.ts'
import { id, type DesktopId } from '../src/protocol.ts'
import type { MobileProfileId } from '../src/profile-capabilities.ts'
import type { DeviceId } from '../src/link-protocol.ts'
import { deviceGrantOperations } from '../src/pairing-protocol.ts'

/** Device proof vocabulary, independent of browser cookies and the operator carrier. */
export const DEVICE_AUTH_PROTOCOL = 'dsh-mobile-device-auth/1'
const operations = deviceGrantOperations
const identifier = z.string().min(1).max(256)
const storedGrant = z.object({ protocol: z.literal(DEVICE_AUTH_PROTOCOL), desktopId: identifier, profileId: identifier,
  deviceId: identifier, credentialId: identifier, epoch: z.number().int().positive().max(Number.MAX_SAFE_INTEGER - 1),
  sessions: z.array(identifier).min(1), operations: z.array(z.enum(operations)).min(1), expiresAt: z.number().int().nonnegative(), revoked: z.boolean() }).strict()
type StoredGrant = z.infer<typeof storedGrant>
/** Public credential identifier; the proof owner holds its key material separately. */
export type DeviceCredentialId = ReturnType<typeof id<'harmony-device-credential'>>
/** Single-use challenge identity, generated by the approved proof owner in a future active composition. */
export type DeviceChallengeId = ReturnType<typeof id<'harmony-device-challenge'>>
/** Cryptographic channel binding identifier supplied by an approved mutually authenticated/encrypted transport. */
export type DeviceChannelBindingId = ReturnType<typeof id<'harmony-device-channel'>>
/** Host-only connection handle; it is never reconstructed from phone JSON or a relay-supplied id. */
export interface DeviceTransportBinding { readonly id: DeviceChannelBindingId; readonly remoteCredentialId: DeviceCredentialId; readonly signal: AbortSignal }
/** Explicit deployment limits; there is no production clock, random source, secret store or listener default. */
export interface DeviceAuthLimits {
  readonly maxGrantTtlMs: number; readonly maxConnectionTtlMs: number; readonly challengeTtlMs: number
  readonly maxDevices: number; readonly maxChallengeIssues: number; readonly maxSessions: number; readonly maxProofBytes: number
}
/** Public challenge binds the signature to this host/profile/device/enrollment/epoch; it grants no operation by itself. */
export interface DeviceChallenge {
  readonly protocol: typeof DEVICE_AUTH_PROTOCOL; readonly challengeId: DeviceChallengeId
  readonly desktopId: DesktopId; readonly profileId: MobileProfileId; readonly deviceId: DeviceId
  readonly credentialId: DeviceCredentialId; readonly epoch: number; readonly expiresAt: number
  readonly channelBindingId: DeviceChannelBindingId
}
/** Required cryptographic implementation; a signature must bind every challenge field, and enrollment must prove possession for the pinned credential and host/profile audience. */
export interface DeviceProofVerifier {
  /** @param candidate - proposed enrollment and its separate host/profile audience. @param signal - authorization attempt lifetime. @returns verified key possession; no bearer/cookie fallback is permitted. */
  enrollment(candidate: { readonly desktopId: DesktopId; readonly profileId: MobileProfileId; readonly deviceId: DeviceId; readonly credentialId: DeviceCredentialId; readonly proof: string }, signal: AbortSignal): Promise<false | { readonly confirmationExpiresAt: number }>
  /** @param authority - exact local confirmation owner. @param candidate - same verified ticket/identity/proof; no remote boolean authorizes it. @returns whether the still-current ticket can activate its public pin after human fingerprint confirmation. */
  confirmEnrollment(authority: object, candidate: Parameters<DeviceProofVerifier['enrollment']>[0]): boolean
  /** @param device - denied device. @returns nothing; clears its public pins and pending tickets without deleting native keys. */
  revoke(device: DeviceId): void
  /** @returns nothing; removes expired public verification state. */
  sweep(): void
  /** @returns nothing; terminally denies verification and releases all public state. */
  close(): void
  /** @param challenge - host-issued single-use audience and epoch. @param signature - bounded untrusted signature. @param signal - connection handshake lifetime. @returns cryptographically verified possession of the pinned enrollment key. */
  challenge(challenge: DeviceChallenge, signature: string, signal: AbortSignal): Promise<boolean>
}
/** Host-owned dependencies; localized copy and proof/identity generation must be supplied explicitly. */
export interface DeviceAuthOptions {
  readonly desktopId: DesktopId; readonly profileId: MobileProfileId; readonly desktopCredentialId: DeviceCredentialId; readonly localAuthority: object; readonly clock: () => number
  readonly limits: DeviceAuthLimits; readonly verifier: DeviceProofVerifier
  readonly identities: { challenge(): DeviceChallengeId }
  readonly copy: { readonly label: string; readonly method: string; readonly allow: string; readonly deny: string; confirm(details: { readonly desktopId: DesktopId; readonly profileId: MobileProfileId; readonly deviceId: DeviceId; readonly desktopCredentialId: DeviceCredentialId; readonly deviceCredentialId: DeviceCredentialId; readonly sessions: readonly string[]; readonly operations: readonly string[]; readonly grantTtlMs: number; readonly confirmationExpiresAt: number }): string }
}
/** Expected, content-free failure; private proof bytes and identifiers never enter error text. */
export class DeviceAuthError extends Error {
  /** @param code - lifecycle/verification refusal. */
  constructor(readonly code: 'local-only' | 'invalid' | 'unpaired' | 'proof-denied' | 'verifier-failed' | 'challenge-stale' | 'scope-changed' | 'expired' | 'capacity' | 'cleanup-failed' | 'closed') { super(code); this.name = 'DeviceAuthError' }
}
/** Host-only lease passed to the narrow carrier, never serialized or exposed as a guest SDK. */
export interface DevicePeerLease { readonly peer: PeerScope; readonly signal: AbortSignal; close(): Promise<void> }
interface Binding { readonly peer: PeerScope; readonly deviceId: DeviceId; readonly epoch: number; readonly expiresAt: number; readonly controller: AbortController; readonly transport: DeviceTransportBinding }

/** Device-specific provider. Cold starts deny all stored grants until a new local confirmation; external record changes deny immediately. */
export class DeviceAuthorizationOwner implements AuthenticatedDeviceProvider {
  private readonly active = new Map<DeviceId, StoredGrant>()
  private readonly bindings = new Map<PeerScope, Binding>()
  private readonly challenges = new Map<DeviceChallengeId, { readonly challenge: DeviceChallenge; readonly transport: DeviceTransportBinding }>()
  private readonly issued = new Set<DeviceChallengeId>()
  private readonly listeners = new Set<(deviceId: DeviceId) => Promise<void>>()
  private readonly keys = new Map<CredentialKey, DeviceId>()
  private readonly versions = new Map<DeviceId, number>()
  private readonly recordVersions = new Map<DeviceId, number>()
  private readonly cleanup = new Map<DeviceId, Promise<void>>()
  private readonly failures = new Set<DeviceId>()
  private readonly handshakes = new Map<DeviceId, Promise<void>>()
  private readonly writes = new Map<DeviceId, Promise<void>>()
  private readonly pairing = new Set<DeviceId>()
  private readonly stopRecords: () => void
  private readonly stopPolicy: () => void
  private readonly lifetime = new AbortController()
  private closed = false
  private closing: Promise<void> | undefined
  /** @param ctx - injected authorization/credentials owner, memory-only in this phase. @param options - explicit policy and trusted proof ports. */
  constructor(private readonly ctx: Context, private readonly options: DeviceAuthOptions) {
    for (const value of Object.values(options.limits)) if (!Number.isSafeInteger(value) || value <= 0) throw new DeviceAuthError('invalid')
    this.stopPolicy = ctx.remoteAccess.registerPolicy('harmony-device', deviceRemotePolicy(principal => {
      for (const peer of this.bindings.keys()) if (peer.principal === principal) return this.current(peer)
      return undefined
    }, options.clock))
    this.stopRecords = ctx.on('credentials/record-updated', key => {
      const device = this.keys.get(key)
      if (device !== undefined) { this.recordVersions.set(device, (this.recordVersions.get(device) ?? 0) + 1); this.active.delete(device); this.retire(device) }
    })
    ctx.effect(() => () => this.close())
  }
  private available(): void { if (this.closed) throw new DeviceAuthError('closed') }
  private async verify<T>(operation: () => Promise<T>): Promise<T> {
    try { return await operation() }
    catch (error) { void error; /* Verifier exceptions may contain submitted proofs; expose only this stable failure. */ throw new DeviceAuthError('verifier-failed') }
  }
  private serialize<T>(device: DeviceId, operation: () => Promise<T>): Promise<T> {
    const next = (this.writes.get(device) ?? Promise.resolve()).then(operation)
    this.writes.set(device, next.then(() => {}, () => {}))
    return next
  }
  private key(deviceId: DeviceId): CredentialKey {
    const digest = createHash('sha256').update(JSON.stringify([this.options.desktopId, this.options.profileId, deviceId])).digest('hex')
    const key = credentialKey('harmony-device', 'device-' + digest); this.keys.set(key, deviceId); return key
  }
  private parseRecord(record: CredentialRecord | undefined): StoredGrant | undefined {
    if (record === undefined) return undefined
    if (record.kind !== 'grant') throw new DeviceAuthError('invalid')
    const parsed = storedGrant.safeParse(record.payload)
    if (!parsed.success || parsed.data.desktopId !== this.options.desktopId || parsed.data.profileId !== this.options.profileId
      || parsed.data.sessions.length > this.options.limits.maxSessions || new Set(parsed.data.sessions).size !== parsed.data.sessions.length
      || parsed.data.sessions.includes('*') || new Set(parsed.data.operations).size !== parsed.data.operations.length) throw new DeviceAuthError('invalid')
    return parsed.data
  }
  private activeGrant(device: DeviceId): StoredGrant {
    this.available()
    const grant = this.active.get(device)
    if (grant === undefined || grant.revoked || this.failures.has(device)) throw new DeviceAuthError('unpaired')
    if (grant.expiresAt <= this.options.clock()) throw new DeviceAuthError('expired')
    return grant
  }
  /** @param device - local selected device. @returns whether the original local confirmation remains active; transport retirement alone does not revoke it. */
  hasLocalGrant(device: DeviceId): boolean { try { this.activeGrant(device); return true } catch (error) { if (error instanceof DeviceAuthError) return false; throw error } }
  /** @param authority - exact local enrollment owner. @param device - selected original device. @returns only its validated public grant record, including a preserved revocation epoch; this grants no live authority. */
  async storedGrant(authority: object, device: DeviceId): Promise<StoredGrant | undefined> { this.available(); if (authority !== this.options.localAuthority) throw new DeviceAuthError('local-only'); const record = this.parseRecord(await this.ctx.credentials.readRecord(this.key(device))); this.available(); return record === undefined ? undefined : structuredClone(record) }
  private retire(device: DeviceId): Promise<void> {
    for (const [challengeId, pending] of this.challenges) if (pending.challenge.deviceId === device) this.challenges.delete(challengeId)
    const old = [...this.bindings.values()].filter(binding => binding.deviceId === device)
    for (const binding of old) { this.bindings.delete(binding.peer); binding.controller.abort() }
    const previous = this.cleanup.get(device) ?? Promise.resolve()
    const task = previous.then(async () => {
      const notifications = await Promise.allSettled(old.length === 0 ? [] : [...this.listeners].map(callback => Promise.resolve().then(() => callback(device))))
      const disposals = await Promise.allSettled(old.map(binding => binding.peer.dispose()))
      if ([...notifications, ...disposals].some(result => result.status === 'rejected')) throw new DeviceAuthError('cleanup-failed')
    })
    this.cleanup.set(device, task)
    void task.catch(() => { this.failures.add(device) })
    return task
  }
  /** @param authority - exact desktop-local capability; never an operator cookie or JSON identity. @param candidate - untrusted proposed key proof and explicitly selected scope. @returns existing authorization flow plus its owned credential key. */
  offerPairing(authority: object, candidate: unknown): AuthorizationFlow {
    this.available(); if (authority !== this.options.localAuthority) throw new DeviceAuthError('local-only')
    const proofText = z.string().min(1).refine(value => new TextEncoder().encode(value).byteLength <= this.options.limits.maxProofBytes)
    const proposal = z.object({ deviceId: identifier, credentialId: identifier, proof: proofText,
      sessions: z.array(identifier).min(1).max(this.options.limits.maxSessions), operations: z.array(z.enum(operations)).min(1).max(operations.length),
      grantTtlMs: z.number().int().positive().max(this.options.limits.maxGrantTtlMs) }).strict().safeParse(candidate)
    if (!proposal.success || new Set(proposal.data.sessions).size !== proposal.data.sessions.length || proposal.data.sessions.includes('*')
      || new Set(proposal.data.operations).size !== proposal.data.operations.length) throw new DeviceAuthError('invalid')
    const selected = proposal.data, deviceId = id<'mobile-device'>(selected.deviceId), credentialId = id<'harmony-device-credential'>(selected.credentialId), key = this.key(deviceId)
    return { key, label: this.options.copy.label, methods: [{ id: 'local-confirmation', label: this.options.copy.method }], run: async session => {
      this.available(); const version = this.versions.get(deviceId) ?? 0
      const pairingSignal = AbortSignal.any([session.signal, this.lifetime.signal]); let confirmationExpiresAt = this.options.clock() + this.options.limits.challengeTtlMs
      const checked = () => { pairingSignal.throwIfAborted(); this.available(); if (this.options.clock() >= confirmationExpiresAt) throw new DeviceAuthError('expired') }
      const proofCandidate = { desktopId: this.options.desktopId, profileId: this.options.profileId, deviceId, credentialId, proof: selected.proof }
      if (new Set([...this.active.keys(), ...this.pairing, deviceId]).size > this.options.limits.maxDevices) throw new DeviceAuthError('capacity')
      this.pairing.add(deviceId)
      try {
      const verified = await this.verify(() => this.options.verifier.enrollment(proofCandidate, pairingSignal))
      if (verified === false) throw new DeviceAuthError('proof-denied')
      confirmationExpiresAt = Math.min(confirmationExpiresAt, verified.confirmationExpiresAt)
      checked()
      const answer = await session.prompt({ kind: 'select', signal: pairingSignal, message: this.options.copy.confirm({ desktopId: this.options.desktopId, profileId: this.options.profileId, deviceId, desktopCredentialId: this.options.desktopCredentialId, deviceCredentialId: credentialId, sessions: selected.sessions, operations: selected.operations, grantTtlMs: selected.grantTtlMs, confirmationExpiresAt }), options: [{ id: 'deny', label: this.options.copy.deny }, { id: 'allow', label: this.options.copy.allow }] })
      if (answer !== 'allow') { this.ctx.authorization.cancel(key); throw new AuthorizationDeclinedError() }
      checked()
      if ((this.versions.get(deviceId) ?? 0) !== version) throw new DeviceAuthError('scope-changed')
      if (!this.active.has(deviceId) && this.active.size >= this.options.limits.maxDevices) throw new DeviceAuthError('capacity')
      await this.serialize(deviceId, async () => {
      checked()
      if ((this.versions.get(deviceId) ?? 0) !== version) throw new DeviceAuthError('scope-changed')
      const old = this.parseRecord(await this.ctx.credentials.readRecord(key))
      checked()
      if (old !== undefined && old.deviceId !== deviceId) throw new DeviceAuthError('invalid')
      if (old !== undefined && old.epoch >= Number.MAX_SAFE_INTEGER - 1) throw new DeviceAuthError('invalid')
      const record: StoredGrant = { protocol: DEVICE_AUTH_PROTOCOL, desktopId: this.options.desktopId, profileId: this.options.profileId,
        deviceId, credentialId, epoch: (old?.epoch ?? 0) + 1, sessions: selected.sessions, operations: selected.operations, expiresAt: this.options.clock() + selected.grantTtlMs, revoked: false }
      if (!storedGrant.safeParse(record).success || (this.versions.get(deviceId) ?? 0) !== version) throw new DeviceAuthError('scope-changed')
      checked(); if (!this.options.verifier.confirmEnrollment(this.options.localAuthority, proofCandidate)) throw new DeviceAuthError('proof-denied')
      await session.commit({ kind: 'grant', payload: record })
      const committedVersion = this.recordVersions.get(deviceId) ?? 0
      await this.cleanup.get(deviceId)
      checked(); if ((this.versions.get(deviceId) ?? 0) !== version || this.failures.has(deviceId) || (this.recordVersions.get(deviceId) ?? 0) !== committedVersion) throw new DeviceAuthError('scope-changed')
      const committed = this.parseRecord(await this.ctx.credentials.readRecord(key))
      checked(); if ((this.versions.get(deviceId) ?? 0) !== version || this.failures.has(deviceId) || (this.recordVersions.get(deviceId) ?? 0) !== committedVersion) throw new DeviceAuthError('scope-changed')
      if (JSON.stringify(committed) !== JSON.stringify(record) || record.expiresAt <= this.options.clock()) throw new DeviceAuthError('scope-changed')
      this.active.set(deviceId, record)
      })
      } finally { this.pairing.delete(deviceId) }
    } }
  }
  /** @param device - enrolled device id. @param transport - exact encrypted carrier connection and cryptographic binding. @returns bounded single-use challenge; caller must prove the pinned key before any Peer exists. */
  async challenge(device: DeviceId, transport: DeviceTransportBinding): Promise<DeviceChallenge> {
    transport.signal.throwIfAborted()
    await this.sweep(); const grant = this.activeGrant(device)
    transport.signal.throwIfAborted()
    if (transport.remoteCredentialId !== grant.credentialId) throw new DeviceAuthError('proof-denied')
    if (this.issued.size >= this.options.limits.maxChallengeIssues) throw new DeviceAuthError('capacity')
    const challengeId = this.options.identities.challenge(); if (this.issued.has(challengeId)) throw new DeviceAuthError('challenge-stale')
    this.issued.add(challengeId)
    const challenge: DeviceChallenge = { protocol: DEVICE_AUTH_PROTOCOL, challengeId, desktopId: this.options.desktopId, profileId: this.options.profileId,
      deviceId: device, credentialId: id<'harmony-device-credential'>(grant.credentialId), epoch: grant.epoch, expiresAt: Math.min(grant.expiresAt, this.options.clock() + this.options.limits.challengeTtlMs), channelBindingId: transport.id }
    this.challenges.set(challengeId, { challenge, transport }); return structuredClone(challenge)
  }
  /** @param candidate - exact challengeId/signature fields; device/peer/cookie/namespace claims reject. @param transport - same exact trusted connection used to issue the challenge. @param signal - handshake lifetime. @returns independent scoped Peer lease after proof and final current-policy recheck. */
  async authenticate(candidate: unknown, transport: DeviceTransportBinding, signal: AbortSignal): Promise<DevicePeerLease> {
    signal = AbortSignal.any([signal, transport.signal, this.lifetime.signal])
    this.available(); signal.throwIfAborted()
    const proof = z.object({ challengeId: identifier, signature: z.string().min(1).refine(value => new TextEncoder().encode(value).byteLength <= this.options.limits.maxProofBytes) }).strict().safeParse(candidate)
    if (!proof.success) throw new DeviceAuthError('invalid')
    const challengeId = id<'harmony-device-challenge'>(proof.data.challengeId), pending = this.challenges.get(challengeId)
    if (pending !== undefined && pending.transport !== transport) throw new DeviceAuthError('proof-denied')
    this.challenges.delete(challengeId)
    const challenge = pending?.challenge
    if (challenge === undefined || challenge.expiresAt <= this.options.clock()) throw new DeviceAuthError('challenge-stale')
    const grant = this.activeGrant(challenge.deviceId)
    if (grant.epoch !== challenge.epoch || grant.credentialId !== challenge.credentialId || transport.remoteCredentialId !== grant.credentialId) throw new DeviceAuthError('scope-changed')
    if (!await this.verify(() => this.options.verifier.challenge(challenge, proof.data.signature, signal))) throw new DeviceAuthError('proof-denied')
    signal.throwIfAborted()
    const previous = this.handshakes.get(challenge.deviceId) ?? Promise.resolve()
    const transition = previous.then(async () => {
    await this.cleanup.get(challenge.deviceId)
    if (this.activeGrant(challenge.deviceId) !== grant || challenge.expiresAt <= this.options.clock()) throw new DeviceAuthError('scope-changed')
    await this.retire(challenge.deviceId)
    if (this.activeGrant(challenge.deviceId) !== grant || challenge.expiresAt <= this.options.clock()) throw new DeviceAuthError('scope-changed')
    signal.throwIfAborted()
    const peer = this.ctx.connection.createPeer({ principal: { kind: 'harmony-device', desktopId: this.options.desktopId, deviceId: challenge.deviceId, epoch: grant.epoch }, interactions: 'none' }), controller = new AbortController()
    this.bindings.set(peer, { peer, controller, transport, deviceId: challenge.deviceId, epoch: grant.epoch, expiresAt: Math.min(grant.expiresAt, this.options.clock() + this.options.limits.maxConnectionTtlMs) })
    peer.ctx.effect(() => async () => {
      if (!this.bindings.delete(peer)) return
      controller.abort()
      const results = await Promise.allSettled([...this.listeners].map(callback => Promise.resolve().then(() => callback(challenge.deviceId))))
      if (results.some(result => result.status === 'rejected')) { this.failures.add(challenge.deviceId); throw new DeviceAuthError('cleanup-failed') }
    })
    peer.ctx.effect(() => {
      const disconnect = () => { this.retire(challenge.deviceId) }
      transport.signal.addEventListener('abort', disconnect, { once: true })
      return () => { transport.signal.removeEventListener('abort', disconnect) }
    })
    return { peer, signal: AbortSignal.any([controller.signal, transport.signal, peer.signal]), close: () => this.disconnect(peer) }
    })
    this.handshakes.set(challenge.deviceId, transition.then(() => {}, () => {}))
    return transition
  }
  /** @param peer - exact authenticated object. @returns detached current policy, or undefined after disconnection, expiry, external edits or revocation. */
  current(peer: PeerScope): AuthenticatedDeviceScope | undefined {
    const binding = this.bindings.get(peer), grant = binding === undefined ? undefined : this.active.get(binding.deviceId)
    if (this.closed || peer.signal.aborted || binding === undefined || grant === undefined || grant.revoked || this.failures.has(binding.deviceId)
      || binding.transport.signal.aborted || grant.epoch !== binding.epoch || Math.min(grant.expiresAt, binding.expiresAt) <= this.options.clock()) return undefined
    return { desktopId: this.options.desktopId, profileId: this.options.profileId, deviceId: binding.deviceId, epoch: grant.epoch, sessions: grant.sessions.map(value => id<'SessionId'>(value)),
      operations: [...grant.operations], expiresAt: Math.min(grant.expiresAt, binding.expiresAt), revoked: false }
  }
  /** @param callback - device cleanup subscriber. @returns Context-owned disposer. */
  onRevoke(callback: (deviceId: DeviceId) => Promise<void>): () => void { return this.ctx.effect(() => { this.listeners.add(callback); return () => { this.listeners.delete(callback) } }) }
  /** @param peer - host-owned transport lease. @returns after connection resources stop; accepted work remains desktop-owned and the unexpired grant can reconnect with fresh proof. */
  async disconnect(peer: PeerScope): Promise<void> { const binding = this.bindings.get(peer); if (binding !== undefined) await this.retire(binding.deviceId) }
  /** @param authority - desktop-local capability. @param device - grant to revoke. @returns after synchronous denial, all cleanup attempts and the owned durable tombstone write; failure never restores admission. */
  async revoke(authority: object, device: DeviceId): Promise<void> {
    if (authority !== this.options.localAuthority) throw new DeviceAuthError('local-only')
    this.available(); this.active.delete(device); this.versions.set(device, (this.versions.get(device) ?? 0) + 1)
    if (this.pairing.has(device)) this.ctx.authorization.cancel(this.key(device))
    let proofFailed = false
    try { this.options.verifier.revoke(device) } catch (error) { void error; proofFailed = true; this.failures.add(device) }
    const cleanup = this.retire(device)
    const write = this.serialize(device, () => this.ctx.credentials.modifyRecord(this.key(device), async current => {
      const old = this.parseRecord(current); if (old === undefined || old.deviceId !== device) throw new DeviceAuthError('unpaired')
      if (old.epoch >= Number.MAX_SAFE_INTEGER - 1) throw new DeviceAuthError('invalid')
      return { kind: 'grant', payload: { ...old, revoked: true, epoch: old.epoch + 1 } }
    }))
    const results = await Promise.allSettled([cleanup, write])
    const failure = results.find(result => result.status === 'rejected'); if (failure?.status === 'rejected') throw failure.reason
    if (proofFailed) throw new DeviceAuthError('cleanup-failed')
  }
  /** @returns after expired grants/connections are denied and cleaned; an active future carrier must own a configured expiry watchdog. */
  async sweep(): Promise<void> {
    this.available(); const now = this.options.clock(), devices = new Set<DeviceId>()
    const expired = new Set<DeviceId>()
    for (const [device, grant] of this.active) if (grant.expiresAt <= now) { this.active.delete(device); devices.add(device); expired.add(device) }
    for (const binding of this.bindings.values()) if (binding.expiresAt <= now || binding.transport.signal.aborted) devices.add(binding.deviceId)
    for (const [key, pending] of this.challenges) if (pending.challenge.expiresAt <= now || pending.transport.signal.aborted) this.challenges.delete(key)
    let proofFailed = false
    for (const device of expired) { try { this.options.verifier.revoke(device) } catch (error) { void error; proofFailed = true; this.failures.add(device) } }
    try { this.options.verifier.sweep() } catch (error) { void error; proofFailed = true }
    const results = await Promise.allSettled([...devices].map(device => this.retire(device)))
    if (proofFailed || results.some(result => result.status === 'rejected')) throw new DeviceAuthError('cleanup-failed')
  }
  /** @returns shared shutdown completion; credentials remain recorded but cold-start policy never restores active admission. */
  close(): Promise<void> {
    if (this.closing !== undefined) return this.closing
    this.closed = true; this.lifetime.abort(); for (const device of this.pairing) this.ctx.authorization.cancel(this.key(device)); this.stopRecords(); this.stopPolicy(); this.challenges.clear(); this.active.clear()
    let proofFailed = false
    try { this.options.verifier.close() } catch (error) { void error; proofFailed = true }
    const devices = new Set([...this.bindings.values()].map(binding => binding.deviceId))
    this.closing = Promise.allSettled([...devices].map(device => this.retire(device)).concat([...this.cleanup.values()])).then(results => {
      this.listeners.clear(); if (proofFailed || results.some(result => result.status === 'rejected')) throw new DeviceAuthError('cleanup-failed')
    })
    return this.closing
  }
}
