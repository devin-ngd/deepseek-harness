/** Four fixed offline responses publish a form, settle one action and leave another explicitly unresolved. */
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import type { Context } from '@deepseek-ai/cordis'
import { ToolCallId, type StreamChunk } from '@deepseek-ai/dsh-llm'
import { installLlmReplay } from '@deepseek-ai/dsh-llm-replay'

const tool = (name: string, args: object): StreamChunk[] => {
  const callId = ToolCallId('workspace-rich-' + name), input = JSON.stringify(args)
  return [{ type: 'block-start', index: 0, blockType: 'tool-call' },
    { type: 'tool-call-delta', index: 0, id: callId, name, argumentsDelta: input },
    { type: 'block-end', index: 0, block: { type: 'tool-call', id: callId, name, arguments: input } }, { type: 'finish', reason: { kind: 'tool-calls' } }]
}
const answer = (text: string): StreamChunk[] => [{ type: 'block-start', index: 0, blockType: 'text' }, { type: 'text-delta', index: 0, text },
  { type: 'block-end', index: 0, block: { type: 'text', text } }, { type: 'finish', reason: { kind: 'stop' } }]
/** @param ctx - synthetic Host. @param world - test-owned directory. @param code - fixed rich form generated by the first replay turn. @param reasoning - optional public synthetic reasoning for a standard renderer contribution. @returns replay consumption checks, with no real provider calls. */
export async function installWorkspaceRichReplay(ctx: Context, world: string, code: object, reasoning?: string) {
  const file = join(world, 'rich-actions.json')
  const first = answer('```rich-html\n' + JSON.stringify(code) + '\n```')
  if (reasoning !== undefined) {
    for (const chunk of first) if ('index' in chunk) chunk.index++
    first.unshift({ type: 'block-start', index: 0, blockType: 'reasoning' }, { type: 'reasoning-delta', index: 0, text: reasoning },
      { type: 'block-end', index: 0, block: { type: 'reasoning', text: reasoning } })
  }
  await writeFile(file, JSON.stringify([
    first,
    tool('rich_inline_complete', { actionId: 'workspace-action-completed', state: 'completed', values: { result: 'OFFLINE_DONE' } }), answer('OFFLINE_COMPLETE'),
    answer('OFFLINE_UNRESOLVED'),
  ].map(chunks => ({ kind: 'chunks', chunks }))) + '\n')
  let calls = 0
  const stop = ctx.on('llm-replay/request', () => { calls++ })
  const handle = installLlmReplay(ctx, { file, overrideFile: file, offline: true,
    providers: [{ id: 'workspace-rich-replay', models: [{ id: 'main', contextWindow: 100000, defaultMaxTokens: 1000 }] }] })
  return { count: () => calls, assertConsumed() { handle.assertConsumed(); ctx.llm.assertOfflineReplayConsumed(); ctx.llm.assertZeroRealCalls() }, dispose() { stop(); handle.dispose() } }
}
